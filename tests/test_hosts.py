"""Host linking preserves unrelated files and validates the whole plan first."""
import contextlib
import importlib.util
import io
from pathlib import Path
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('hosts', ROOT / 'scripts/hosts.py')
hosts = importlib.util.module_from_spec(spec)
spec.loader.exec_module(hosts)


class HostLinkTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name).resolve()
        self.dest = self.root / 'host'
        self.skills = hosts.components(ROOT / 'plugins/10x-swe')[0]

    def tearDown(self):
        self.temp.cleanup()

    def link(self, host='agents', unlink=False, dry_run=False):
        with contextlib.redirect_stdout(io.StringIO()):
            return hosts.link(host, self.dest, ['10x-swe'], unlink, dry_run)

    def test_unrelated_repo_symlink_is_neither_replaced_nor_removed(self):
        target = self.dest / 'skills' / self.skills[0].name
        target.parent.mkdir(parents=True)
        target.symlink_to(ROOT / 'README.md')
        with self.assertRaisesRegex(SystemExit, 'not managed'):
            self.link()
        self.link(unlink=True)
        self.assertEqual(target.resolve(), ROOT / 'README.md')

    def test_late_conflict_leaves_no_partial_installation(self):
        conflict = self.dest / 'skills' / self.skills[-1].name
        conflict.parent.mkdir(parents=True)
        conflict.write_text('user skill')
        with self.assertRaisesRegex(SystemExit, 'not managed'):
            self.link()
        self.assertEqual(list(conflict.parent.iterdir()), [conflict])
        self.assertEqual(conflict.read_text(), 'user skill')

    def test_symlinked_discovery_directory_is_not_written_through(self):
        external = self.root / 'external'
        external.mkdir()
        self.dest.mkdir()
        (self.dest / 'skills').symlink_to(external, target_is_directory=True)
        with self.assertRaisesRegex(SystemExit, 'symlink'):
            self.link()
        self.assertEqual(list(external.iterdir()), [])

    def test_link_repeat_dry_run_and_unlink(self):
        self.link(host='opencode', dry_run=True)
        self.assertFalse(self.dest.exists())
        self.link(host='opencode')
        agent = self.dest / 'agents/code-reviewer.md'
        data, body = hosts.parse_frontmatter(agent)
        self.assertEqual(data['mode'], 'subagent')
        self.assertIn('Generated by 10x-swe', body)
        before = agent.read_bytes()
        self.link(host='opencode')
        self.assertEqual(agent.read_bytes(), before)
        self.link(host='opencode', unlink=True)
        self.assertFalse(agent.exists())
        self.assertEqual(list((self.dest / 'skills').iterdir()), [])


if __name__ == '__main__':
    unittest.main()
